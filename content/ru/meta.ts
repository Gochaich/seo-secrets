export const metaByPath = new Map(pagesMeta.map((page) => [page.path, page]));

/**
 * Метаданные страницы по её пути. Путь неизвестен — это ошибка сборки,
 * а не повод молча отдать пустой заголовок: страницу либо забыли добавить
 * в карту, либо ошиблись в адресе.
 */
export function pageMeta(path: string): PageMeta {
  const found = metaByPath.get(path);
  if (!found) {
    throw new Error(
      `Нет метаданных для «${path}». Добавьте страницу в content/ru/meta.ts.`,
    );
  }
  return found;
}
