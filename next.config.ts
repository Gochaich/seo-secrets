import createNextIntlPlugin from 'next-intl/plugin';
import type { NextConfig } from 'next';

const nextConfig: NextConfig = {
  /**
   * Адреса на Tilda заканчиваются слэшем: /o-nas/, /team/, /case-study/.
   * Без этого флага Next.js редиректит /o-nas/ на /o-nas — то есть на переезде
   * поменялись бы ВСЕ адреса сайта. Ровно то, чего мы не должны допустить.
   */
  trailingSlash: true,

  /*
   * Встраивание CSS в разметку (experimental.inlineCss) пробовали и убрали.
   *
   * Замысел был верный: убрать единственный блокирующий отрисовку запрос,
   * на который жаловался PageSpeed. По эмуляции медленной сети выходило
   * вдвое быстрее до первой отрисовки.
   *
   * На боевом замере PageSpeed стало хуже. Правдоподобная причина: HTML
   * вырастал с 56 до 79 КБ в сжатом виде — Next кладёт стили дважды, тегом
   * style и ещё раз в полезной нагрузке. Эмуляция полосы у себя на машине
   * не воспроизводит разгон TCP-соединения, и лишние 23 КБ там обходились
   * дешевле, чем на настоящей сети с задержкой.
   *
   * Вывод: замер на боевом деплое важнее замера в эмуляции. Если возвращать —
   * то по одной правке за раз, с проверкой PageSpeed после каждой.
   */

  images: {
    // Отдаём современные форматы — заметная часть выигрыша в скорости против Тильды
    formats: ['image/avif', 'image/webp'],

    // remotePatterns здесь больше нет и быть не должно: все картинки лежат
    // в /public/images. Сайт не зависит ни от тарифа Тильды, ни от сторонних
    // сервисов иконок. Долг из docs/AUDIT.md, п. 10, закрыт 19 августа.
  },

  /**
   * Заголовки безопасности. Отдаются на каждый ответ сайта.
   *
   * Их не было ни одного — сайт статический, красть с него нечего, но два
   * сценария реальны и без базы данных. Первый: чужая страница открывает наш
   * сайт в невидимом фрейме поверх своих кнопок, и посетитель жмёт «Связаться
   * с нами», думая, что жмёт что-то другое. Второй: браузер сам угадывает тип
   * файла и исполняет как скрипт то, что скриптом не является.
   *
   * Список внешних адресов собран по фактической выдаче, а не по памяти:
   * единственный сторонний ресурс на сайте — плееры YouTube. Шрифты Next
   * складывает к себе при сборке, картинки все свои, запросов на чужие
   * домены страница не делает. Ссылки на сайты клиентов — это href,
   * загрузкой они не являются и в политику не входят.
   */
  async headers() {
    /*
     * script-src приходится держать с 'unsafe-inline'. Next.js кладёт в разметку
     * несколько встроенных <script> для гидратации, а строгая политика требует
     * на каждый nonce — который можно выдать только при отрисовке на запрос.
     * Страницы у нас статические, и переводить их в динамику ради этого значит
     * менять быстрый сайт на медленный. Остальные директивы при этом строгие,
     * и главное — frame-ancestors и object-src закрыты наглухо.
     *
     * Когда на этапе 7 появятся счётчики, сюда добавятся их адреса:
     *   GA4      script-src + connect-src: https://www.googletagmanager.com
     *                        connect-src: https://*.google-analytics.com
     *   Метрика  script-src: https://mc.yandex.ru
     *            connect-src: https://mc.yandex.ru
     *            img-src:     https://mc.yandex.ru
     */
    const csp = [
      "default-src 'self'",
      "script-src 'self' 'unsafe-inline'",
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob:",
      "font-src 'self'",
      "connect-src 'self'",
      // Видео-отзывы и записи выступлений
      "frame-src https://www.youtube-nocookie.com https://www.youtube.com",
      // Форма на контактах уходит в WhatsApp, пока нет своего обработчика
      "form-action 'self' https://wa.me",
      // Плагин или инъекция не сможет переписать базовый адрес ссылок
      "base-uri 'none'",
      "object-src 'none'",
      // Никто не имеет права открыть наш сайт во фрейме
      "frame-ancestors 'none'",
      'upgrade-insecure-requests',
    ].join('; ');

    return [
      {
        source: '/:path*',
        headers: [
          { key: 'Content-Security-Policy', value: csp },
          // Дубль frame-ancestors для браузеров, которые его не знают
          { key: 'X-Frame-Options', value: 'DENY' },
          // Тип файла берётся из заголовка, а не угадывается по содержимому
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          // На чужие сайты уходит только домен, без пути и меток кампаний
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          // Сайту не нужны ни камера, ни микрофон, ни геолокация
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=(), payment=()',
          },
          /*
           * Год на HTTPS. Без includeSubDomains намеренно: под доменом могут
           * жить почта или панель без сертификата, и правило их отрежет.
           * preload тоже не ставим — это запись в список браузеров, откуда
           * не выйти быстро. Оба варианта включаются отдельным решением.
           */
          {
            key: 'Strict-Transport-Security',
            value: 'max-age=31536000',
          },
        ],
      },
    ];
  },

  async redirects() {
    // Таблица 301-редиректов со старых адресов Тильды.
    // Заполняется на этапе 7 из карты URL, собранной на этапе 1.
    // Формат: { source: '/staryj-adres', destination: '/novyj-adres', permanent: true }
    return [];
  },
};

const withNextIntl = createNextIntlPlugin();

export default withNextIntl(nextConfig);
