/**
 * Разметка schema.org для страницы.
 *
 * Вставить JSON в <script> обычным JSON.stringify нельзя. Браузер закрывает
 * тег на первом же `</script>` внутри строки — и всё, что идёт дальше,
 * перестаёт быть данными и становится живой разметкой. Достаточно, чтобы
 * в тексте на странице кто-то написал `</script>`, и страница ломается,
 * а при недобром тексте — исполняется чужой код.
 *
 * Тексты у нас свои, из файлов в content/, так что прямо сейчас это не дыра.
 * Но правит их не только разработчик: над проектом работают два ИИ-агента,
 * а дальше тексты будут править руками. Экранирование стоит одну строку —
 * дешевле, чем однажды разбираться, почему страница поехала.
 *
 * Экранируем `<` как <: внутри JSON это тот же символ, но разборщик
 * HTML его уже не видит. Заодно закрываем разделители строк U+2028 и U+2029 —
 * в JSON они допустимы, а в JavaScript до ES2019 ломали разбор.
 */
const ESCAPED: Record<string, string> = {
  '<': '\\u003c',
  '\u2028': '\\u2028',
  '\u2029': '\\u2029',
};

export function JsonLd({ data }: { data: object }) {
  const json = JSON.stringify(data).replace(
    /[<\u2028\u2029]/g,
    (char) => ESCAPED[char],
  );

  return (
    <script
      type="application/ld+json"
      // Строка собрана нами из типизированных данных и экранирована выше.
      dangerouslySetInnerHTML={{ __html: json }}
    />
  );
}
